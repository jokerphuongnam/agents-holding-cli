import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const root = new URL("../full/client/scripts/terminal.mjs", import.meta.url).pathname;
const holding = new URL("../full/client/scripts/holding", import.meta.url).pathname;
const home = mkdtempSync(join(tmpdir(), "ah-terminal-")), repo = join(home, "repo");
execFileSync("mkdir", ["-p", repo]);
const run = (cwd, ...a) => execFileSync(process.execPath, [root, ...a], { cwd, env: { ...process.env, HOME: home, AH_COMPANY: "", AGENTS_HOLDING_DEVICE: "device-test", AH_TERMINAL_TEST_METADATA: "1" }, encoding: "utf8" });
assert.throws(() => run(home, "link", "bad", "--repo", repo, "--company", "marlin-language"), /invalid terminal token/);
assert.throws(() => run(home, "link", "ahterm_12345678", "--repo", repo), /wrong repo\/cwd/);
const marlin = JSON.parse(run(repo, "register", "--company", "marlin-language", "--repo", repo));
const nail = JSON.parse(run(repo, "register", "--company", "nailly", "--repo", repo));
assert.equal(marlin.status, "connected");
assert.equal(nail.status, "connected");
const configDir = join(home, ".config/agents-holding");
mkdirSync(configDir, { recursive: true });
writeFileSync(join(configDir, "projects.json"), JSON.stringify({ version: 1, projects: [{ name: "repo", path: repo, boards: [{ project_key: "MARLIN", company: "marlin-language" }] }] }));
const inferred = JSON.parse(run(repo, "register", "--repo", repo));
assert.equal(inferred.company, "marlin-language");
const marlinList = run(repo, "status", "--company", "marlin-language");
assert.match(marlinList, new RegExp(marlin.session_id));
assert.match(marlinList, new RegExp(inferred.session_id));
assert.doesNotMatch(marlinList, new RegExp(nail.session_id));
assert.doesNotMatch(run(repo, "status"), new RegExp(nail.session_id));
writeFileSync(join(configDir, "projects.json"), JSON.stringify({ version: 1, projects: [{ name: "repo", path: repo, boards: [{ project_key: "MARLIN", company: "marlin-language" }, { project_key: "NAIL", company: "nailly" }] }] }));
assert.throws(() => run(repo, "register", "--repo", repo), /company is ambiguous/);
assert.throws(() => run(repo, "status"), /company is ambiguous/);
const nailList = run(repo, "status", "--company", "nailly");
assert.match(nailList, new RegExp(nail.session_id));
assert.doesNotMatch(nailList, new RegExp(marlin.session_id));
assert.throws(() => run(repo, "status", "--company", "nailly", marlin.session_id), /not registered in company nailly/);
assert.throws(() => run(repo, "dispatch", "--company", "nailly", marlin.session_id, "./run_tests.sh"), /not registered in company nailly/);
assert.throws(() => run(home, "status"), /no company context/);
const scopedCli = (args) => spawnSync("bash", [holding, ...args], { cwd: repo, encoding: "utf8", env: { ...process.env, HOME: home, AH_NO_UPDATE_CHECK: "1", AH_TERMINAL_SESSION_ID: marlin.session_id, AH_COMPANY: "marlin-language" } });
const allStaff = scopedCli(["staff", "list", "--all"]);
assert.equal(allStaff.status, 2);
assert.match(allStaff.stderr, /--all is unavailable in a company-registered terminal/);
const crossCompanyRun = scopedCli(["staff", "run", "tech-lead", "inspect", "--company", "nailly"]);
assert.equal(crossCompanyRun.status, 2);
assert.match(crossCompanyRun.stderr, /terminal is scoped to company marlin-language/);
const switchCompany = scopedCli(["company", "use", "nailly"]);
assert.equal(switchCompany.status, 2);
assert.match(switchCompany.stderr, /company switching\/listing is unavailable/);
assert.match(run(repo, "heartbeat", "--company", "marlin-language", marlin.session_id), /heartbeat ok/);
assert.match(run(repo, "unregister", "--company", "marlin-language", marlin.session_id), /unregistered/);
assert.match(run(repo, "status", "--company", "marlin-language", marlin.session_id), /unregistered/);
console.log("terminal_cli_test: pass");
