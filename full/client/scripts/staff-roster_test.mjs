import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { localStaff, reconcileStaff, overLimitError, rosterEntry } from "./staff-roster.mjs";
let passed = 0;
const ok = (name, cond) => { assert.ok(cond, name); console.log("ok", name); passed++; };
const home = mkdtempSync(join(tmpdir(), "ah-staff-home-")), repo = mkdtempSync(join(tmpdir(), "ah-staff-repo-"));
mkdirSync(join(repo, ".agents/acme/system/staffs/engineering"), { recursive: true });
writeFileSync(join(repo, ".agents/acme/COMPANY.md"), "# Acme\n");
writeFileSync(join(repo, ".agents/acme/system/staffs/engineering/local-hacker.md"), "name: local-hacker\n");
mkdirSync(join(repo, ".agents/acme/roles/private/secret-reviewer"), { recursive: true });
writeFileSync(join(repo, ".agents/acme/roles/private/secret-reviewer/AGENT.md"), "private persona\n");
const local = localStaff(repo, "acme", home);
ok("detects hand-created staff under .agents/<company>", local.some((r) => r.name === "local-hacker"));
ok("detects company-created private roles without uploading names", local.some((r) => r.name === "secret-reviewer" && r.id.startsWith("private-role-") && r.id.length === 25));
const rows = reconcileStaff(local, { roster: ["ceo", "a", "b"], limit: 3 });
ok("marks local-only staff inactive over the plan cap", rows.every((r) => !r.active && r.status === "not active (over plan limit)"));
ok("exact required over-limit error", rows[0].error === overLimitError(rows[0].name, 3, 3));
ok("grandfathered local staff remain active", reconcileStaff([{ name: "old", id: "old" }], { roster: ["ceo", "a", "b", "old"], limit: 3 })[0].active);
ok("private role uses only opaque id for server check", rosterEntry(local, "secret-reviewer").id.startsWith("private-role-"));
console.log(`staff-roster_test: ${passed} passed`);
